#!/usr/bin/env node
/**
 * Generate `src/lib/fy27-roles.generated.ts` from the canonical FY27 role
 * schema (`docs/fy27-migration/foundry_roles_schema.json`).
 *
 * The schema JSON is the single source of truth for the FY27 role
 * architecture (same file `generate_seed.py` reads to build the SQL seed).
 * Never hand-edit the generated .ts file — change the schema and re-run:
 *
 *   node scripts/gen-fy27-roles.mjs
 *
 * Keeps the app taxonomy, the DB seed, and the position descriptions from
 * drifting apart. See FY27_ROLE_ARCHITECTURE.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'docs/fy27-migration/foundry_roles_schema.json');
const OUT = join(ROOT, 'src/lib/fy27-roles.generated.ts');

const schema = JSON.parse(readFileSync(SRC, 'utf8'));

const bandCode = (name) => name.toUpperCase().replace(/ /g, '_');

/** Incentive target % from the role's incentive text; null if not eligible. */
function targetPct(role) {
  const txt = (role.incentive ?? '').toLowerCase();
  if (txt.includes('not incentive-eligible') || txt.includes('not applicable')) return null;
  const m = /(\d+)\s*%/.exec(role.incentive ?? '');
  return m ? Number(m[1]) : null;
}

const POOL_CODE = {
  'Associate Partner / Manager Pool': 'POOL_APM',
  'Consultant Pool': 'POOL_CONSULT',
  'Expert / Fellow Pool': 'POOL_EXPFEL',
  'Analyst Pool': 'POOL_ANALYST',
};

const bands = schema.bands.map((b) => ({
  code: bandCode(b.band),
  name: b.band,
  notes: b.notes ?? null,
}));

const roles = schema.roles.map((r) => {
  const et = r.engagement_types ?? [];
  return {
    code: r.code,
    title: r.title,
    bandCode: bandCode(r.band),
    seniorityRank: r.seniority_rank,
    dualPathway: Boolean(r.dual_pathway),
    permitsPermanent: et.includes('permanent') || et.includes('equity_partner'),
    permitsContractor: et.includes('contractor'),
    permitsProgram: et.includes('program'),
    permitsHonorary: et.includes('honorary'),
    remunerationModel: r.remuneration_model,
    incentiveTargetPct: targetPct(r),
  };
});

const poolRoles = [];
for (const p of schema.team_structure.talent_pools) {
  const code = POOL_CODE[p.pool];
  if (!code) throw new Error(`Unmapped talent pool: ${p.pool}`);
  for (const roleCode of p.codes) poolRoles.push({ poolCode: code, roleCode });
}

const banner = `// AUTO-GENERATED by scripts/gen-fy27-roles.mjs — DO NOT EDIT BY HAND.
// Source of truth: docs/fy27-migration/foundry_roles_schema.json (schema ${schema.meta.version}).
// Re-generate with:  node scripts/gen-fy27-roles.mjs
`;

const body = `${banner}
export const FY27_SCHEMA_VERSION = ${JSON.stringify(schema.meta.version)} as const;
export const FY27_EFFECTIVE_FROM = ${JSON.stringify(schema.meta.effective_from)} as const;

export const FY27_BANDS = ${JSON.stringify(bands, null, 2)} as const;

export const FY27_ROLES = ${JSON.stringify(roles, null, 2)} as const;

export const FY27_POOL_ROLES = ${JSON.stringify(poolRoles, null, 2)} as const;
`;

writeFileSync(OUT, body);
console.log(
  `wrote ${OUT} — ${roles.length} roles, ${bands.length} bands, ${poolRoles.length} pool-role links (schema ${schema.meta.version})`,
);
